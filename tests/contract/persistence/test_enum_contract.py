"""Every enum column's permitted values equal the Python enum's values.

This is the test that catches someone adding a ``JobStatus`` member without a migration.

It works by parsing the DDL that SQLAlchemy generates for each ``CHECK`` constraint in
:data:`scout_persistence.tables.ENUM_SPECS` and comparing the recovered value set with
``[member.value for member in enum]``. The DDL is the artefact Alembic autogenerates from
and the artefact PostgreSQL enforces, so asserting against it binds the database to the
python vocabulary rather than binding the test to a copy of the vocabulary.

Altering a native PostgreSQL ``ENUM`` is painful and irreversible; a ``VARCHAR`` plus a
named ``CHECK`` is a plain migration. That tradeoff only pays off if the constraint and
the enum cannot drift, which is what these tests guarantee.
"""

from __future__ import annotations

import re
from enum import Enum
from typing import Any

import pytest
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from scout_persistence.tables import (
    ENUM_COLUMN_WIDTH,
    ENUM_SPECS,
    WEBHOOK_EVENT_STATUSES,
    Base,
)

DIALECT = postgresql.dialect()

#: Matches ``col IN ('A', 'B')``, tolerating the double quotes SQLAlchemy emits when a
#: value needs escaping. Anchored on ``IN`` so a range check such as
#: ``authority_rank BETWEEN 0 AND 5`` is not mistaken for a vocabulary list.
_IN_CLAUSE = re.compile(r"^\s*(?P<column>[\w\"]+)\s+IN\s*\((?P<values>.*)\)\s*$", re.DOTALL)
_QUOTED = re.compile(r"'((?:[^']|'')*)'")


def check_constraints(table_name: str) -> dict[str, str]:
    """Return ``{constraint_name: sql_text}`` for every check constraint on a table."""
    table = Base.metadata.tables[table_name]
    found: dict[str, str] = {}
    for constraint in table.constraints:
        if constraint.__class__.__name__ != "CheckConstraint":
            continue
        assert constraint.name is not None, f"{table_name} has an unnamed check constraint"
        found[constraint.name] = str(constraint.sqltext)
    return found


def permitted_values(ddl_text: str) -> tuple[str, list[str]]:
    """Recover ``(column, values)`` from a ``col IN (...)`` check constraint.

    Unquoting uses SQL's own escape rule (``''`` is a literal apostrophe) so a value that
    ever needed escaping is read back exactly as PostgreSQL would read it.
    """
    match = _IN_CLAUSE.match(ddl_text)
    assert match is not None, f"not a vocabulary constraint: {ddl_text!r}"
    column = match.group("column").strip('"')
    values = [raw.replace("''", "'") for raw in _QUOTED.findall(match.group("values"))]
    return column, values


def compiled_ddl(table_name: str) -> str:
    """Return the PostgreSQL ``CREATE TABLE`` statement for a table."""
    return str(CreateTable(Base.metadata.tables[table_name]).compile(dialect=DIALECT))


def test_every_enum_column_has_a_check_constraint() -> None:
    """Each registered enum column is constrained in the DDL that will be created.

    Read from the compiled statement rather than from the ``Table`` object, so a
    constraint that SQLAlchemy silently failed to render still fails this test.
    """
    missing: list[str] = []
    for (table_name, column_name), _enum in ENUM_SPECS.items():
        ddl = compiled_ddl(table_name)
        if f"ck_{table_name}_{column_name}_values" not in ddl:
            missing.append(f"{table_name}.{column_name}")
    assert missing == [], f"enum columns with no CHECK constraint: {missing}"


@pytest.mark.parametrize(
    ("table_name", "column_name"),
    sorted(ENUM_SPECS),
    ids=str,
)
def test_check_constraint_values_equal_the_python_enum(
    table_name: str,
    column_name: str,
) -> None:
    """The permitted values in the database are exactly the Python enum's values.

    Ordered comparison as well as set comparison: the constraint text is generated by
    iterating the enum, so a reordering means someone hand-edited the constraint or the
    enum's declaration order changed — either is worth knowing about before it reaches a
    migration.
    """
    enum: type[Enum] = ENUM_SPECS[(table_name, column_name)]
    constraints = check_constraints(table_name)
    constraint_name = f"ck_{table_name}_{column_name}_values"
    assert constraint_name in constraints, (
        f"{table_name} has no {constraint_name}; found {sorted(constraints)}"
    )

    parsed_column, values = permitted_values(constraints[constraint_name])
    assert parsed_column == column_name
    assert values == [member.value for member in enum], (
        f"{table_name}.{column_name}: database permits {values}, "
        f"{enum.__name__} declares {[member.value for member in enum]}. "
        "A new enum member needs a migration."
    )


@pytest.mark.parametrize(
    ("table_name", "column_name"),
    sorted(ENUM_SPECS),
    ids=str,
)
def test_every_enum_member_is_representable_in_the_column(
    table_name: str,
    column_name: str,
) -> None:
    """No permitted value is wider than the column that stores it."""
    enum: type[Enum] = ENUM_SPECS[(table_name, column_name)]
    column: Any = Base.metadata.tables[table_name].c[column_name]
    declared_length = column.type.length
    assert declared_length is not None, f"{table_name}.{column_name} has no declared length"
    longest = max(len(member.value) for member in enum)
    assert longest <= declared_length, (
        f"{table_name}.{column_name} is String({declared_length}) but "
        f"{enum.__name__} has a {longest}-character value"
    )
    assert declared_length >= ENUM_COLUMN_WIDTH or longest <= declared_length


def test_all_enum_columns_are_registered() -> None:
    """The registry and the schema agree in both directions.

    A ``CHECK ... IN (...)`` constraint on a column that is not in ``ENUM_SPECS`` would
    mean the vocabulary test does not cover it. The webhook receipt status is the single
    deliberate exception: it is not a domain enum, so it is declared beside the table and
    covered by its own test below.
    """
    registered = {(table, column) for table, column in ENUM_SPECS}
    vocabulary_constraints: set[tuple[str, str]] = set()
    skipped = {("webhook_events", "status")}

    for table in Base.metadata.sorted_tables:
        for name, text in check_constraints(table.name).items():
            if not _IN_CLAUSE.match(text):
                continue
            column, _values = permitted_values(text)
            if name.endswith("_values"):
                vocabulary_constraints.add((table.name, column))

    assert vocabulary_constraints - registered <= skipped, (
        f"constrained columns missing from ENUM_SPECS: "
        f"{sorted(vocabulary_constraints - registered - skipped)}"
    )
    assert registered <= vocabulary_constraints


def test_webhook_status_constraint_matches_its_python_constant() -> None:
    """The delivery-receipt vocabulary is pinned even though it is not a domain enum."""
    _column, values = permitted_values(
        check_constraints("webhook_events")["ck_webhook_events_status_values"]
    )
    assert values == list(WEBHOOK_EVENT_STATUSES)


def test_job_status_constraint_lists_every_state() -> None:
    """``JobStatus`` specifically, because it is the one expected to grow.

    Stated separately from the parametrised test so the failure message for the most
    likely future change — a new job state — is unambiguous.
    """
    from scout_domain.enums import JobStatus

    _column, values = permitted_values(
        check_constraints("verification_jobs")["ck_verification_jobs_status_values"]
    )
    assert set(values) == {status.value for status in JobStatus}
    assert len(values) == len(JobStatus)


def test_check_constraints_are_named_by_the_metadata_convention() -> None:
    """Every constraint name is ``ck_<table>_<something>``.

    Alembic compares constraints by name, so an unnamed or inconsistently named
    constraint produces "drop unnamed / add unnamed" churn in the next autogenerated
    migration and cannot be dropped deliberately in a later one.
    """
    for table in Base.metadata.sorted_tables:
        for constraint in table.constraints:
            assert constraint.name, f"{table.name} has an unnamed constraint"
            if constraint.__class__.__name__ == "CheckConstraint":
                assert constraint.name.startswith(f"ck_{table.name}_"), (
                    f"{constraint.name!r} does not follow ck_{table.name}_<name>"
                )


def test_index_names_follow_the_metadata_convention() -> None:
    """Every index name is ``ix_<table>_<columns>``."""
    for table in Base.metadata.sorted_tables:
        for index in table.indexes:
            assert index.name is not None
            assert index.name.startswith(f"ix_{table.name}_"), (
                f"{index.name!r} does not follow ix_{table.name}_<columns>"
            )


def test_foreign_key_names_follow_the_metadata_convention() -> None:
    """Every foreign key name is ``fk_<table>_<columns>_<referred table>``."""
    for table in Base.metadata.sorted_tables:
        for constraint in table.constraints:
            if constraint.__class__.__name__ != "ForeignKeyConstraint":
                continue
            assert constraint.name is not None
            assert constraint.name.startswith(f"fk_{table.name}_")


def test_primary_key_names_follow_the_metadata_convention() -> None:
    """Every primary key is named ``pk_<table>``."""
    for table in Base.metadata.sorted_tables:
        assert table.primary_key.name == f"pk_{table.name}"
