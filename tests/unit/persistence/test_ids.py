"""Identifier contracts: prefixes, width, and what the tables accept.

Scout's identifiers are prefixed ULIDs generated by the caller, never by the database
(``scout_domain.ids``). Two properties of that scheme are load-bearing and are pinned
here:

* **A prefixed identifier fits its column.** ``String(64)`` holds ``job_`` plus 26
  Crockford base32 characters. A future ``IdKind`` with a longer prefix would still fit,
  but a repository that accidentally wrote a composite key would not — so the width is
  asserted, not assumed.
* **The prefix is the per-kind prefix, not a generic one.** ``webhook_events.id`` must
  start ``whr_`` and not ``job_``; a copy-pasted ``new_id(IdKind.JOB)`` in a repository
  would otherwise produce rows whose ids lie about what they are, in logs and URLs, long
  before anyone notices.

The last test reads the prefix each of Scout's own repositories mints, so a new
repository that reuses the wrong ``IdKind`` fails here rather than in production.
"""

from __future__ import annotations

import inspect

import pytest

from scout_domain.ids import IdKind, new_id, new_ulid, validate_ulid
from scout_persistence.tables import Base

#: Every table whose primary key holds a prefixed ULID. Listed explicitly so a new table
#: without an id has to change this test rather than pass it by accident.
TABLES_WITH_PREFIXED_IDS: tuple[str, ...] = (
    "agent_runs",
    "approvals",
    "artifacts",
    "audit_events",
    "engineering_decisions",
    "findings",
    "job_stages",
    "knowledge_documents",
    "knowledge_embeddings",
    "model_requests",
    "notifications",
    "question_answers",
    "questions",
    "repositories",
    "sandbox_runs",
    "tool_runs",
    "verification_jobs",
    "webhook_events",
)

#: Which identifier kind each table's primary key is minted from. This is the mapping a
#: repository is expected to use; the tests below prove both that each kind produces the
#: prefix its table expects, and that Scout's repositories use these kinds.
TABLE_ID_KINDS: dict[str, IdKind] = {
    "agent_runs": IdKind.AGENT_RUN,
    "approvals": IdKind.APPROVAL,
    "artifacts": IdKind.ARTIFACT,
    "audit_events": IdKind.AUDIT_EVENT,
    "engineering_decisions": IdKind.DECISION,
    "findings": IdKind.FINDING,
    "job_stages": IdKind.STAGE,
    "knowledge_documents": IdKind.KNOWLEDGE_DOCUMENT,
    "knowledge_embeddings": IdKind.KNOWLEDGE_DOCUMENT,
    "model_requests": IdKind.MODEL_REQUEST,
    "notifications": IdKind.NOTIFICATION,
    "question_answers": IdKind.ANSWER,
    "questions": IdKind.QUESTION,
    "repositories": IdKind.REPOSITORY,
    "sandbox_runs": IdKind.SANDBOX_RUN,
    "tool_runs": IdKind.TOOL_RUN,
    "verification_jobs": IdKind.JOB,
    "webhook_events": IdKind.WEBHOOK_EVENT,
}


def test_table_id_kind_map_covers_every_table() -> None:
    """Every table with an ``id`` has a declared identifier kind."""
    assert set(TABLE_ID_KINDS) == set(TABLES_WITH_PREFIXED_IDS)
    assert set(TABLES_WITH_PREFIXED_IDS) == set(Base.metadata.tables)


@pytest.mark.parametrize("table", TABLES_WITH_PREFIXED_IDS)
def test_generated_id_starts_with_the_prefix_the_table_expects(table: str) -> None:
    """``new_id(kind)`` produces the exact prefix the table's repository will write."""
    kind = TABLE_ID_KINDS[table]
    generated = new_id(kind)
    expected_prefix = f"{kind.value}_"
    assert generated.startswith(expected_prefix)
    assert generated.count("_") == 1, "a prefix must not itself contain an underscore"
    assert validate_ulid(generated.removeprefix(expected_prefix))


@pytest.mark.parametrize("table", TABLES_WITH_PREFIXED_IDS)
def test_generated_id_fits_the_primary_key_column(table: str) -> None:
    """A generated identifier is narrower than the ``String(64)`` that holds it.

    Checked against the real column rather than a constant, so widening a prefix or
    narrowing a column is caught here.
    """
    column = Base.metadata.tables[table].c["id"]
    length = column.type.length  # type: ignore[attr-defined]
    assert length is not None, f"{table}.id must declare a length"
    generated = new_id(TABLE_ID_KINDS[table])
    assert len(generated) <= length, (
        f"{generated!r} ({len(generated)} chars) does not fit {table}.id String({length})"
    )


def test_every_id_kind_has_a_table() -> None:
    """Every ``IdKind`` member is used by exactly one table.

    ``KNOWLEDGE_DOCUMENT`` is the one intentional exception: spec section 42 declares a
    ``knowledge_embeddings`` table but the domain never gave embeddings a kind of their
    own, so an embedding row reuses the document kind. The assertion below records that
    deliberately rather than tolerating an unnoticed duplicate.
    """
    used = set(TABLE_ID_KINDS.values())
    duplicated = {
        kind for kind in IdKind if sum(1 for v in TABLE_ID_KINDS.values() if v is kind) > 1
    }
    assert duplicated == {IdKind.KNOWLEDGE_DOCUMENT}
    assert used == set(IdKind)


def test_prefixed_id_prefixes_are_unique() -> None:
    """No two kinds share a prefix, so an identifier is unambiguous in a log line."""
    prefixes = [kind.value for kind in IdKind]
    assert len(prefixes) == len(set(prefixes))


def test_ids_are_monotonic_and_sortable() -> None:
    """Two ids created in sequence sort in creation order.

    ULIDs exist for this: it keeps B-tree indexes dense and makes an audit trail readable
    without a join. A regression to random ids would still be unique but would break
    ``ORDER BY id`` as a proxy for creation order, which several read paths rely on.
    """
    ids = [new_ulid() for _ in range(50)]
    assert ids == sorted(ids)
    assert len(set(ids)) == len(ids)


def test_repository_id_kinds_match_the_map() -> None:
    """Scout's repositories mint the identifier kind their table expects.

    Read from the source of each repository module rather than by executing it, because
    the point is to check what is *written at the call site*. A repository that mints the
    wrong kind produces ids that look plausible and sort correctly while being
    mislabelled everywhere they appear.
    """
    from scout_persistence import repositories

    expected_by_module: dict[str, IdKind] = {
        "scout_persistence.repositories.webhook_event": IdKind.WEBHOOK_EVENT,
        "scout_persistence.repositories.stage": IdKind.STAGE,
        "scout_persistence.repositories.approval": IdKind.APPROVAL,
        "scout_persistence.repositories.question": IdKind.ANSWER,
        "scout_persistence.repositories.repository": IdKind.REPOSITORY,
        "scout_persistence.repositories.audit": IdKind.AUDIT_EVENT,
    }

    import importlib

    for module_name, kind in expected_by_module.items():
        module = importlib.import_module(module_name)
        source = inspect.getsource(module)
        assert f"new_id(IdKind.{kind.name})" in source, (
            f"{module_name} does not mint {kind.name} ids"
        )

    # The repository package exposes exactly the classes the unit of work binds.
    assert repositories.__all__


def test_prefixed_id_length_is_within_the_documented_column() -> None:
    """The longest possible prefixed id is bounded by the widest prefix plus a ULID."""
    longest_prefix = max(len(kind.value) for kind in IdKind)
    assert longest_prefix + 1 + 26 <= 64
